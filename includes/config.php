<?php
/**
 * Configuration load/save.
 *
 * The configuration is stored as a PHP file that `return`s an array. This is
 * deliberate: even if the file were ever served directly by a misconfigured
 * web server, PHP would execute it and output nothing instead of leaking the
 * key as plain text. The config directory is additionally denied by .htaccess.
 */

if (!defined('LVS_ROOT')) {
    http_response_code(500);
    exit('Direct access is not allowed.');
}

function lvs_config_defaults()
{
    return array(
        'openrouter_api_key'      => '',
        'http_referer'            => 'http://localhost/local-video-studio/',
        'app_title'               => 'Local AI Video Studio',
        'poll_interval_seconds'   => 10,
        'max_local_storage_mb'    => 1024,
        'max_history_entries'     => 200,
        'request_timeout_seconds' => 60,
        'generation_timeout_seconds' => 900,
        'max_upload_mb'           => 8,
        'allow_local_save'        => true,
        'enable_rate_limit'       => true,
        'generations_per_minute'  => 6,
    );
}

function lvs_config_path()
{
    return LVS_CONFIG_DIR . '/config.php';
}

/**
 * Load the merged configuration (defaults + saved values).
 *
 * @return array
 */
function lvs_load_config()
{
    $defaults = lvs_config_defaults();
    $path = lvs_config_path();

    if (is_file($path)) {
        $loaded = @include $path;
        if (is_array($loaded)) {
            return array_merge($defaults, $loaded);
        }
    }

    return $defaults;
}

/**
 * Persist configuration values atomically with restrictive permissions.
 *
 * @param array $values
 * @return bool
 */
function lvs_save_config(array $values)
{
    $path = lvs_config_path();
    $export = var_export($values, true);
    $php = "<?php\n"
        . "// Auto-generated by Local AI Video Studio. Keep this file private.\n"
        . "// This file is ignored by git and blocked from web access.\n\n"
        . "return " . $export . ";\n";

    $tmp = $path . '.tmp';
    if (@file_put_contents($tmp, $php, LOCK_EX) === false) {
        return false;
    }
    @chmod($tmp, 0600);
    if (!@rename($tmp, $path)) {
        @unlink($tmp);
        return false;
    }
    @chmod($path, 0600);
    return true;
}

function lvs_config_has_key()
{
    $cfg = lvs_load_config();
    return isset($cfg['openrouter_api_key']) && $cfg['openrouter_api_key'] !== '';
}
